"""
Comprehensive Automated Test Suite for Smart Alert Explanation Engine
Validates:
1. Warning generated by real configured rules (Tachycardia, Bradycardia, Prolonged QTc, Reduced HRV).
2. Critical alerts (Ventricular Tachycardia, Ventricular Fibrillation, Asystole).
3. Evidence assembly (observed measurements, units, thresholds, status).
4. Handling alerts with POOR SIGNAL / artifacts.
5. Missing measurements or unavailable prediction data handled gracefully without crashes.
6. Legacy alerts without explanation_json fallback safely.
7. Unidentified trigger condition fallback.
8. Persistence to SQLite database and retrieval via AlertSystem / REST endpoint.
"""

import time
import pytest
import numpy as np

from backend.alert_explanation import smart_alert_explainer, SmartAlertExplainer
from backend.alert_system import alert_system, AlarmPriority
from backend.database import DatabaseManager


class TestSmartAlertExplanation:

    def setup_method(self):
        self.explainer = SmartAlertExplainer()

    def test_warning_generated_by_heart_rate_tachycardia(self):
        """HR > 150 must trigger Severe Tachycardia rule with accurate evidence."""
        alert_dict = {
            "alert_id": "ALT-TEST-TACHY",
            "patient_id": "BED-01",
            "priority": "WARNING",
            "trigger_condition": "Severe Tachycardia (HR > 150)",
            "timestamp": "12:00:00"
        }
        vitals = {"hr": 165}
        metrics = {"heart_rate": 165, "qrs_duration_ms": 90.0, "qtc_ms": 410.0}
        ai_diag = {"diagnosis": "Sinus Tachycardia", "confidence": 0.94}
        sig_qual = {"status": "GOOD SIGNAL", "score": 95}

        explanation = self.explainer.generate_explanation(
            alert=alert_dict,
            vitals=vitals,
            metrics=metrics,
            ai_diagnosis=ai_diag,
            signal_quality=sig_qual,
            trigger_rule="tachycardia_high"
        )

        assert explanation["explanation_available"] is True
        assert "165" in explanation["observed_measurement"] or "165" in explanation["summary_explanation"]
        assert "Tachycardia" in explanation["rule_title"]
        assert explanation["signal_quality_status"] == "GOOD SIGNAL"
        assert len(explanation["supporting_evidence"]) > 0
        # Verify evidence contains HR check
        hr_ev = next((e for e in explanation["supporting_evidence"] if "Heart Rate" in e["parameter"]), None)
        assert hr_ev is not None
        assert "165" in hr_ev["observed_value"]
        assert hr_ev["rule_status"] == "TRIGGERED"

    def test_critical_alert_ventricular_tachycardia(self):
        """Model VT or acute VT injection must explain life-threatening ventricular arrhythmia."""
        alert_dict = {
            "alert_id": "ALT-TEST-VT",
            "patient_id": "BED-01",
            "priority": "HIGH PRIORITY (CRISIS / CODE BLUE)",
            "trigger_condition": "Sustained Ventricular Tachycardia",
            "timestamp": "12:05:00"
        }
        vitals = {"hr": 178}
        metrics = {"heart_rate": 178, "qrs_duration_ms": 142.0, "qtc_ms": 490.0}
        ai_diag = {"diagnosis": "Ventricular Tachycardia", "confidence": 0.96}
        sig_qual = {"status": "GOOD SIGNAL", "score": 92}

        explanation = self.explainer.generate_explanation(
            alert=alert_dict,
            vitals=vitals,
            metrics=metrics,
            ai_diagnosis=ai_diag,
            signal_quality=sig_qual
        )

        assert "Ventricular Tachycardia" in explanation["rule_title"]
        assert explanation["model_result"] == "Ventricular Tachycardia (96.0% confidence)"
        assert "178" in explanation["observed_measurement"]
        assert "CRISIS" in explanation["alert_severity"] or "HIGH PRIORITY" in explanation["alert_severity"]

    def test_alert_with_poor_signal_quality_annotates_limitation(self):
        """When signal quality is POOR SIGNAL or REVIEW, explanation must explicitly caution clinician."""
        alert_dict = {
            "alert_id": "ALT-TEST-POOR",
            "patient_id": "BED-02",
            "priority": "WARNING",
            "trigger_condition": "Frequent Premature Ventricular Contractions (PVCs)",
            "timestamp": "12:10:00"
        }
        vitals = {"hr": 80}
        metrics = {"heart_rate": 80}
        ai_diag = {"diagnosis": "Premature Ventricular Contractions", "confidence": 0.70}
        sig_qual = {"status": "POOR SIGNAL", "score": 42, "primary_reason": "Severe high-frequency artifact"}

        explanation = self.explainer.generate_explanation(
            alert=alert_dict,
            vitals=vitals,
            metrics=metrics,
            ai_diagnosis=ai_diag,
            signal_quality=sig_qual
        )

        assert explanation["signal_quality_status"] == "POOR SIGNAL"
        # Summary must include cautionary limitation note
        assert "caution" in explanation["summary_explanation"].lower() or "artifact" in explanation["summary_explanation"].lower() or "unreliable" in explanation["summary_explanation"].lower()

    def test_missing_measurements_handled_gracefully(self):
        """Missing or None measurements must display 'Not available' without crashing."""
        alert_dict = {
            "alert_id": "ALT-TEST-MISSING",
            "patient_id": "BED-03",
            "priority": "ADVISORY",
            "trigger_condition": "Elevated Clinical Early Warning Score (CEWI)",
            "timestamp": "12:15:00"
        }
        # Completely empty vitals and metrics
        explanation = self.explainer.generate_explanation(
            alert=alert_dict,
            vitals=None,
            metrics=None,
            ai_diagnosis=None,
            signal_quality=None
        )

        assert explanation["explanation_available"] is True
        assert explanation["model_result"] == "Not available"
        assert explanation["signal_quality_status"] == "Not available"
        assert len(explanation["supporting_evidence"]) > 0

    def test_unidentified_rule_trigger_states_reason_unavailable(self):
        """An alert with an unknown custom trigger condition must not invent fabricated numbers."""
        alert_dict = {
            "alert_id": "ALT-TEST-UNKNOWN",
            "patient_id": "BED-01",
            "priority": "ADVISORY",
            "trigger_condition": "Unknown Custom Engineering Alert X7",
            "timestamp": "12:20:00"
        }
        explanation = self.explainer.generate_explanation(alert=alert_dict)

        assert explanation["explanation_available"] is True
        assert "Unknown Custom Engineering Alert X7" in explanation["triggering_condition"]
        # Must not fabricate values
        assert explanation["model_result"] == "Not available"

    def test_legacy_alert_backward_compatibility(self):
        """Alerts without explanation_json or created prior to feature must format cleanly."""
        legacy_alert = {
            "alert_id": "LEGACY-ALERT-001",
            "patient_id": "BED-01",
            "priority": "WARNING",
            "trigger_condition": "Sinus Bradycardia",
            "timestamp": "10:00:00"
        }
        expl = self.explainer.generate_explanation(alert=legacy_alert)

        assert expl["explanation_available"] is True
        assert expl["alert_id"] == "LEGACY-ALERT-001"
        assert expl["alert_severity"] == "WARNING"

    def test_persistence_and_retrieval(self):
        """Saved emergency episode with explanation_json retrieves structured explanation."""
        episode_id = f"EP-TEST-{int(time.time() * 1000)}"
        explanation_data = {
            "summary_explanation": "Persistent Ventricular Tachycardia triggered emergency alarm.",
            "rule_title": "Ventricular Tachycardia (VT)",
            "rule_condition": "Model diagnosis VT with HR > 100 bpm",
            "observed_measurement": "180 bpm",
            "model_result": "Ventricular Tachycardia",
            "signal_quality_status": "GOOD SIGNAL",
            "explanation_available": True
        }

        # Save to database
        DatabaseManager.create_episode(
            episode_id=episode_id,
            patient_id="BED-01",
            condition="Ventricular Tachycardia",
            priority="HIGH PRIORITY (CRISIS / CODE BLUE)",
            smart_explanation=explanation_data
        )

        # Retrieve and verify
        retrieved = DatabaseManager.get_episode(episode_id)
        assert retrieved is not None
        assert "smart_explanation" in retrieved
        assert retrieved["smart_explanation"] is not None
        assert retrieved["smart_explanation"]["rule_title"] == "Ventricular Tachycardia (VT)"
        assert retrieved["smart_explanation"]["observed_measurement"] == "180 bpm"

    def test_alert_system_get_alert_explanation(self):
        """ClinicalAlertSystem.get_alert_explanation returns explanation for active or history alert."""
        # Trigger an alert through alert_system
        alert = alert_system.evaluate_and_trigger(
            patient_id="BED-01",
            rhythm="Severe Tachycardia",
            heart_rate=165,
            vitals={"hr": 165, "bp_sys": 120, "bp_dia": 80, "spo2": 98},
            cewi_score=65,
            metrics={"heart_rate": 165, "technical_quality_status": "GOOD SIGNAL", "snr_db": 22.0},
            ai_diagnosis={"diagnosis": "Sinus Tachycardia", "confidence": 0.95}
        )

        if alert:
            expl = alert_system.get_alert_explanation(alert["alert_id"])
            assert expl is not None
            assert expl["explanation_available"] is True
            assert "Tachycardia" in expl["rule_title"] or "Tachycardia" in expl["triggering_condition"]
